# GIMS load-test runner (Windows PowerShell).
#
#   powershell -ExecutionPolicy Bypass -File .\scripts\run.ps1 -Script load -Profile smoke
#   powershell -ExecutionPolicy Bypass -File .\scripts\run.ps1 -Script load -Profile small
#   powershell -ExecutionPolicy Bypass -File .\scripts\run.ps1 -Script login -Profile smoke
#
# Stop a running test with Ctrl+C or, from another shell:
#   powershell -ExecutionPolicy Bypass -File .\scripts\stop.ps1

param(
    [ValidateSet("load", "login", "frontend")]
    [string]$Script = "load",

    [ValidateSet("smoke", "small", "medium", "target")]
    [string]$Profile = "smoke",

    [string]$ApiBaseUrl,
    [string]$FrontendUrl
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot

# 1. Optional local defaults from load-testing/.env (KEY=VALUE lines).
$envFile = Join-Path $root ".env"
if (Test-Path $envFile) {
    foreach ($line in Get-Content $envFile) {
        $trimmed = $line.Trim()
        if ($trimmed -eq "" -or $trimmed.StartsWith("#")) { continue }
        $separator = $trimmed.IndexOf("=")
        if ($separator -lt 1) { continue }
        $key = $trimmed.Substring(0, $separator).Trim()
        $value = $trimmed.Substring($separator + 1).Trim()
        if (-not (Test-Path "Env:$key")) { Set-Item -Path "Env:$key" -Value $value }
    }
}

# 2. Command-line overrides beat .env.
if ($ApiBaseUrl) { $env:API_BASE_URL = $ApiBaseUrl }
if ($FrontendUrl) { $env:FRONTEND_URL = $FrontendUrl }
if (-not $env:API_BASE_URL) { $env:API_BASE_URL = "http://127.0.0.1:8000" }
if (-not $env:FRONTEND_URL) { $env:FRONTEND_URL = "https://gims-dole12.vercel.app" }

$env:PROFILE = $Profile
$env:RUN_ID = "$(Get-Date -Format 'yyyyMMdd-HHmmss')-$Profile"

# 3. Accounts: JSON file (generated by the provisioning script) or ACCOUNTS_JSON.
if (-not $env:ACCOUNTS_JSON) {
    $accountsPath = Join-Path $root "accounts.json"
    if (-not (Test-Path $accountsPath)) {
        throw "accounts.json not found. Run: php .\provision\provision-test-accounts.php --count=20"
    }
    $env:ACCOUNTS_FILE = $accountsPath.Replace("\", "/")
}

# 4. Results directory for the report files written by handleSummary().
$resultsDir = Join-Path $root "results"
New-Item -ItemType Directory -Force -Path $resultsDir | Out-Null

# 5. Locate k6: portable install first, then PATH.
$k6 = Join-Path $root ".tools\k6.exe"
if (-not (Test-Path $k6)) {
    $command = Get-Command k6 -ErrorAction SilentlyContinue
    if ($command) {
        $k6 = $command.Source
    } else {
        throw "k6 not found. Run: powershell -ExecutionPolicy Bypass -File .\scripts\install-k6.ps1"
    }
}

$entry = switch ($Script) {
    "load" { "scripts/load-test.js" }
    "login" { "scripts/login-test.js" }
    "frontend" { "scripts/frontend-smoke.js" }
}

Write-Host ""
Write-Host "GIMS load test (read-only, dedicated test accounts)" -ForegroundColor Cyan
Write-Host "  script      : $Script"
Write-Host "  profile     : $Profile"
Write-Host "  backend     : $env:API_BASE_URL"
Write-Host "  frontend    : $(if ($env:ENABLE_FRONTEND_CHECKS -eq '1') { $env:FRONTEND_URL } else { 'not exercised (backend-only)' })"
Write-Host "  results     : $resultsDir"
Write-Host ""
Write-Host "  Stop with Ctrl+C, or run .\scripts\stop.ps1 from another shell." -ForegroundColor Yellow
Write-Host ""

Push-Location $root
try {
    & $k6 run $entry
    $exitCode = $LASTEXITCODE
} finally {
    Pop-Location
}

if ($exitCode -ne 0) {
    Write-Host ""
    Write-Host "k6 exited with code $exitCode (a failed threshold keeps this non-zero)." -ForegroundColor Yellow
    exit $exitCode
}

Write-Host ""
Write-Host "Done. Report: $resultsDir\$env:RUN_ID-report.md" -ForegroundColor Green
